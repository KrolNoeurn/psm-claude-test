from decimal import ROUND_HALF_UP, Decimal

from django.conf import settings
from django.db import models

from apps.accounts.models import Branch
from apps.catalog.models import ProductUnit
from apps.inventory.models import StockBatch


class ShopSettings(models.Model):
    """Single row of shop-wide options (receipt header, VAT, alerts)."""

    shop_name = models.CharField(max_length=120, default="Pharmacy")
    shop_name_km = models.CharField(max_length=120, blank=True)
    address = models.CharField(max_length=255, blank=True)
    phone = models.CharField(max_length=60, blank=True)
    receipt_footer = models.CharField(
        max_length=255, blank=True, default="សូមអរគុណ / Thank you"
    )
    receipt_width = models.CharField(
        max_length=4, choices=[("80", "80 mm"), ("58", "58 mm")], default="80"
    )
    vat_enabled = models.BooleanField(default=False)
    vat_rate = models.DecimalField(max_digits=5, decimal_places=2, default=Decimal("10.00"))
    expiry_alert_days = models.PositiveIntegerField(default=30)

    class Meta:
        verbose_name_plural = "shop settings"

    @classmethod
    def load(cls):
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj

    def save(self, *args, **kwargs):
        self.pk = 1
        super().save(*args, **kwargs)

    def __str__(self):
        return self.shop_name


class ExchangeRate(models.Model):
    """Riel per US dollar. The newest row is the rate in use."""

    khr_per_usd = models.DecimalField(max_digits=10, decimal_places=2)
    effective_at = models.DateTimeField(auto_now_add=True)
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT
    )

    class Meta:
        ordering = ["-effective_at", "-id"]

    @classmethod
    def current(cls):
        latest = cls.objects.first()
        return latest.khr_per_usd if latest else Decimal("4000")

    def __str__(self):
        return f"1 USD = {self.khr_per_usd} KHR"


class Sale(models.Model):
    """A completed sale. Amounts are in USD; KHR is derived with `exchange_rate`."""

    class Type(models.TextChoices):
        RETAIL = "retail", "Retail"
        WHOLESALE = "wholesale", "Wholesale"

    class Status(models.TextChoices):
        COMPLETED = "completed", "Completed"
        VOIDED = "voided", "Voided"

    number = models.CharField(max_length=30, unique=True)
    client_uuid = models.UUIDField(
        unique=True, help_text="Generated by the POS so an offline sale is saved only once"
    )
    sale_type = models.CharField(max_length=10, choices=Type.choices, default=Type.RETAIL)
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.COMPLETED)
    branch = models.ForeignKey(Branch, on_delete=models.PROTECT, related_name="sales")
    cashier = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="sales"
    )
    approved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT,
        related_name="approved_sales", help_text="Pharmacist who approved controlled drugs",
    )
    customer_name = models.CharField(max_length=120, blank=True)
    customer_phone = models.CharField(max_length=40, blank=True)
    subtotal = models.DecimalField(max_digits=12, decimal_places=2)
    discount = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0"))
    vat_rate = models.DecimalField(max_digits=5, decimal_places=2, default=Decimal("0"))
    vat_amount = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0"))
    total = models.DecimalField(max_digits=12, decimal_places=2)
    paid = models.DecimalField(max_digits=12, decimal_places=2)
    change_usd = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0"))
    exchange_rate = models.DecimalField(max_digits=10, decimal_places=2)
    prescription_image = models.FileField(upload_to="prescriptions/%Y/%m/", blank=True)
    note = models.CharField(max_length=255, blank=True)
    sold_at = models.DateTimeField(help_text="When the cashier completed it (may be offline)")
    created_at = models.DateTimeField(auto_now_add=True)
    voided_at = models.DateTimeField(null=True, blank=True)
    voided_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT,
        related_name="voided_sales",
    )
    void_reason = models.CharField(max_length=255, blank=True)

    class Meta:
        ordering = ["-sold_at", "-id"]

    def __str__(self):
        return self.number

    @property
    def total_khr(self):
        return round_khr(self.total * self.exchange_rate)


class SaleItem(models.Model):
    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="items")
    product_unit = models.ForeignKey(ProductUnit, on_delete=models.PROTECT)
    qty = models.PositiveIntegerField(help_text="Quantity in the sold unit")
    base_qty = models.PositiveIntegerField(help_text="Quantity in base units")
    unit_price = models.DecimalField(max_digits=12, decimal_places=2)
    discount = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0"))
    line_total = models.DecimalField(max_digits=12, decimal_places=2)
    cost = models.DecimalField(
        max_digits=12, decimal_places=4, help_text="Cost of goods from the batches used"
    )

    def __str__(self):
        return f"{self.qty} x {self.product_unit}"


class SaleItemBatch(models.Model):
    """Which batches a sale line was taken from (FEFO may split a line)."""

    item = models.ForeignKey(SaleItem, on_delete=models.CASCADE, related_name="batches")
    batch = models.ForeignKey(StockBatch, on_delete=models.PROTECT)
    qty = models.PositiveIntegerField(help_text="Base units")
    unit_cost = models.DecimalField(max_digits=12, decimal_places=4)


class Payment(models.Model):
    class Method(models.TextChoices):
        CASH_USD = "cash_usd", "Cash USD"
        CASH_KHR = "cash_khr", "Cash KHR"
        KHQR = "khqr", "KHQR"

    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="payments")
    method = models.CharField(max_length=10, choices=Method.choices)
    amount = models.DecimalField(
        max_digits=14, decimal_places=2, help_text="In the payment's own currency"
    )
    currency = models.CharField(max_length=3, choices=[("USD", "USD"), ("KHR", "KHR")])
    amount_usd = models.DecimalField(max_digits=12, decimal_places=2)
    reference = models.CharField(max_length=80, blank=True, help_text="KHQR transaction id")

    def __str__(self):
        return f"{self.method} {self.amount} {self.currency}"


def round_khr(amount):
    """Riel is paid in 100-riel steps."""
    return (Decimal(amount) / 100).quantize(Decimal("1"), rounding=ROUND_HALF_UP) * 100
